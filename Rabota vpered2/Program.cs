public class Program
{
    public static void Main(string[] args )
    {
        ///1.Создаем первый обьект
        Student student1 = new Student();
        ///2.Заполняем его поля данными!
        student1.firstName = "Губка";
        student1.lastName = "Боб";
        student1.age = 100;

        ///3.Создаем второй обьект!
        Student student2 = new Student();
        ///4.Заполняем поля для второго обьекта!
        student2.firstName = "Патрик";
        student2.lastName = "Звезда";
        student2.age = 1000;

        Console.WriteLine("Представляеться первый житель Бикини-Ботам");
