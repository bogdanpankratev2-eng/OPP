//программа представляеться как совокупность взаимодействия обьектов.
//Каждый обьект явл. экземпляром определенного класса и инкакпсулирует в себе
//как данные (поля) , ьак и  процедуры для их обработки (методы)


//ООП состоит из 3 китах!!!
//Инкапсуляция: Обьеденение данных и методов для их
//обработки в одном компоненте (обьектов) и сокрытие
//деталей реалезации от внешнего мира. Обьект - это черный ящик,
//который предостовляет  наружу только удобный интерфейс!


//Наследование: Механизм, который позволяет создавать
//новый класс на основе существуещего, перенимая его
//свойства и поведение и добавляя свои. (Например классы, "Грузовик"
//и "Легковой автомобиль" могут наследовать
//общие свойства от класса "автомобиля")!!!!


//Полиморфизм: Способность обьектов с одаковым
//интерфейсом (например, с методом Move()) иметь
//различную реализацию этого интерфейса. (Например,
//Move() для обьекта "Рыба" будет означать "плыть", а для обекта птица "летать"


