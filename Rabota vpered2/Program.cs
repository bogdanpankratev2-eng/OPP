public class Student
{
    public string firstName;
    public string lastName;
    public int age;
    public double temperatura;
    public void Introduce()
    {
        Console.WriteLine($"Всем привет. Меня зовут:{firstName}.\nМоя Фамилия:{lastName}.\nМне:{age}лет." +
            $"\nМоя температура:{temperatura}");
    }

}
